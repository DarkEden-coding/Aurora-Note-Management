// Generates LucideIcons.kt from the same lucide-react icon data the web app renders,
// so both clients draw identical icons. Run: node apps/android/tools/generate-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const icons = [
  "MousePointer2", "LassoSelect", "Hand", "Pen", "Highlighter", "Eraser", "Type", "Slash", "Square", "Circle",
  "ArrowUpRight", "Brackets", "Undo2", "Redo2", "ClipboardPaste", "Camera", "PanelLeftClose", "PanelLeftOpen",
  "Search", "Trash2", "ChevronRight", "ChevronDown", "Folder", "FolderOpen", "FolderPlus", "Plus", "FileText",
  "Wifi", "WifiOff", "Calculator", "Settings", "RefreshCw", "Lock", "Unlock", "Copy", "CopyPlus", "Scissors",
  "BringToFront", "SendToBack", "X", "Heart", "Star", "RotateCcw", "Delete", "Settings2", "Pencil", "Check",
  "ArrowRight", "LoaderCircle",
];

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])([0-9])/g, "$1-$2").toLowerCase();

function iconNode(name, file = resolve(root, `node_modules/lucide-react/dist/esm/icons/${kebab(name)}.mjs`)) {
  const source = readFileSync(file, "utf8");
  // Some names are aliases that re-export another icon module.
  const alias = source.match(/export \{ default \} from '\.\/(.+?)'/);
  if (alias) return iconNode(name, resolve(dirname(file), alias[1]));
  const literal = source.match(/const __iconNode = (\[[\s\S]*?\]);\n/)[1];
  return Function(`return ${literal}`)();
}

const n = (v) => Number(v ?? 0);

function toPath([tag, a]) {
  switch (tag) {
    case "path": return a.d;
    case "circle": { const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
    case "ellipse": { const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)];
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
    case "line": return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? d + "Z" : d;
    }
    case "rect": {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
      const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    default: throw new Error(`Unsupported element ${tag}`);
  }
}

const entries = icons.map((name) => {
  const paths = iconNode(name).map(toPath).map((d) => `"${d}"`).join(",\n        ");
  return `    val ${name}: ImageVector by lazy {\n        lucide(\n            "${name}",\n            ${paths},\n        )\n    }`;
});

const kotlin = `// Generated by apps/android/tools/generate-icons.mjs from lucide-react ${JSON.parse(readFileSync(resolve(root, "node_modules/lucide-react/package.json"), "utf8")).version}. Do not edit by hand.
package app.aurora.notes.ui

import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp
import androidx.compose.ui.graphics.Color

/** Lucide's 24-unit, 2-unit-stroke outline icons; tint them with Icon(tint = ...). */
private fun lucide(name: String, vararg paths: String): ImageVector {
    val builder = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f)
    for (d in paths) {
        builder.addPath(
            pathData = PathParser().parsePathString(d).toNodes(),
            fill = null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 2f,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }
    return builder.build()
}

object Lucide {
${entries.join("\n\n")}
}
`;
writeFileSync(resolve(root, "apps/android/app/src/main/java/app/aurora/notes/ui/LucideIcons.kt"), kotlin);
console.log(`Wrote ${icons.length} icons`);
